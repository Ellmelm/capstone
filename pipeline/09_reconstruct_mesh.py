
# -*- coding: utf-8 -*-
"""Create a floor mesh from the original walkable grid and optional wall meshes.

Usage:
  python pipeline/10_reconstruct_mesh.py output/<scan>/aligned.pcd output/<scan>
  python pipeline/10_reconstruct_mesh.py output/<scan>/aligned.pcd output/<scan> --no-walls

Preferred floor source:
  output/<scan>/walkable.npz

The original grid mask, origin, cell size and floor elevations are reused.
Triangles are formed only from local neighboring grid cells, avoiding
Delaunay connections across large holes.
"""

import argparse
import json
import sys
from pathlib import Path

import numpy as np
import open3d as o3d


def fail(message):
    print("ERROR:", message, file=sys.stderr)
    sys.exit(1)


def load_cloud(path):
    cloud = o3d.io.read_point_cloud(str(path))

    if cloud.is_empty():
        raise ValueError(
            "Point cloud is empty or cannot be read: {}".format(path)
        )

    points = np.asarray(cloud.points)
    finite = np.isfinite(points).all(axis=1)
    cloud = cloud.select_by_index(np.flatnonzero(finite))

    if len(cloud.points) < 30:
        raise ValueError(
            "Not enough valid points in point cloud: {}".format(path)
        )

    return cloud


def triangle_area(tri):
    return 0.5 * np.linalg.norm(
        np.cross(tri[1] - tri[0], tri[2] - tri[0])
    )


def triangle_max_edge(tri):
    lengths = [
        np.linalg.norm(tri[0] - tri[1]),
        np.linalg.norm(tri[1] - tri[2]),
        np.linalg.norm(tri[2] - tri[0]),
    ]
    return float(max(lengths))


def make_mesh(vertices, faces):
    if not faces:
        raise ValueError(
            "No floor triangles were created. Check walkable.npz, "
            "floor elevations, and the edge limit."
        )

    mesh = o3d.geometry.TriangleMesh()
    mesh.vertices = o3d.utility.Vector3dVector(
        np.asarray(vertices, dtype=np.float64)
    )
    mesh.triangles = o3d.utility.Vector3iVector(
        np.asarray(faces, dtype=np.int32)
    )

    mesh.remove_degenerate_triangles()
    mesh.remove_duplicated_triangles()
    mesh.remove_unreferenced_vertices()
    mesh.compute_vertex_normals()

    if len(mesh.triangles) == 0:
        raise ValueError("The resulting floor mesh contains no triangles.")

    return mesh


def floor_mesh_from_grid(npz_path, max_edge):
    """Build the floor from the exact grid generated by 02_walkable.py."""

    npz_path = Path(npz_path)

    with np.load(str(npz_path)) as data:
        mask = data["mask"].astype(bool)
        floor_z = np.asarray(data["floor_z"], dtype=np.float64)
        mins = np.asarray(data["mins"], dtype=np.float64)
        cell = float(data["cell"])

    if mask.ndim != 2 or floor_z.shape != mask.shape:
        raise ValueError(
            "Invalid walkable.npz: mask and floor_z must have "
            "the same 2D shape."
        )

    if mins.shape[0] < 2 or cell <= 0:
        raise ValueError("Invalid grid origin or cell size in walkable.npz.")

    if not mask.any():
        raise ValueError("walkable.npz contains no walkable cells.")

    if not np.isfinite(floor_z[mask]).all():
        raise ValueError("Non-finite floor elevations found in the grid.")

    ni, nj = mask.shape

    # One vertex at the centre of every selected grid cell.
    cell_to_vertex = {}
    vertices = []

    for i, j in np.argwhere(mask):
        z = float(floor_z[i, j])

        vertex_id = len(vertices)
        cell_to_vertex[(int(i), int(j))] = vertex_id

        vertices.append([
            float(mins[0] + (i + 0.5) * cell),
            float(mins[1] + (j + 0.5) * cell),
            z,
        ])

    vertices = np.asarray(vertices, dtype=np.float64)

    # Build triangles locally from each 2x2 grid block.
    # Four present cells form a quad split into two triangles.
    # Exactly three present cells can form one local triangle.
    # Blocks with fewer than three cells are left open.
    candidate_count = 0
    rejected_edge_count = 0
    rejected_area_count = 0
    faces = []

    def add_triangle(cell_a, cell_b, cell_c):
        nonlocal candidate_count
        nonlocal rejected_edge_count
        nonlocal rejected_area_count

        ids = [
            cell_to_vertex[cell_a],
            cell_to_vertex[cell_b],
            cell_to_vertex[cell_c],
        ]

        tri = vertices[ids]
        candidate_count += 1

        if triangle_max_edge(tri) > max_edge:
            rejected_edge_count += 1
            return

        area = triangle_area(tri)

        if not np.isfinite(area) or area < 1e-10:
            rejected_area_count += 1
            return

        faces.append(ids)

    for i in range(ni - 1):
        for j in range(nj - 1):
            a = (i, j)
            b = (i + 1, j)
            c = (i, j + 1)
            d = (i + 1, j + 1)

            present = [
                key for key in (a, b, c, d)
                if key in cell_to_vertex
            ]

            if len(present) < 3:
                continue

            if len(present) == 3:
                add_triangle(present[0], present[1], present[2])
                continue

            # Choose the shorter 3D diagonal for a more stable split.
            diagonal_ad = np.linalg.norm(
                vertices[cell_to_vertex[a]] -
                vertices[cell_to_vertex[d]]
            )
            diagonal_bc = np.linalg.norm(
                vertices[cell_to_vertex[b]] -
                vertices[cell_to_vertex[c]]
            )

            if diagonal_ad <= diagonal_bc:
                add_triangle(a, b, d)
                add_triangle(a, d, c)
            else:
                add_triangle(a, b, c)
                add_triangle(b, d, c)

    mesh = make_mesh(vertices, faces)

    print("Floor source:", npz_path)
    print("Original grid shape:", mask.shape)
    print("Grid cell size: {:.3f} m".format(cell))
    print("Walkable grid cells:", int(mask.sum()))
    print("Candidate local triangles:", candidate_count)
    print("Rejected triangles (edge limit):", rejected_edge_count)
    print("Rejected degenerate triangles:", rejected_area_count)
    print("Accepted floor triangles:", len(mesh.triangles))
    print("Floor mesh area: {:.3f} m2".format(mesh.get_surface_area()))

    return mesh, cell, "walkable.npz"


def floor_mesh_from_cloud(walk, grid, max_edge):
    """Fallback for folders without walkable.npz.

    This method is less reliable because it reconstructs a new grid
    from the walkable point cloud.
    """

    from scipy.spatial import Delaunay, QhullError

    points = np.asarray(walk.points, dtype=float)
    points = points[np.isfinite(points).all(axis=1)]

    if len(points) < 3:
        raise ValueError("Need at least 3 valid walkable points.")

    xy = points[:, :2]
    xy_min = xy.min(axis=0)
    cell_indices = np.floor((xy - xy_min) / grid).astype(np.int64)

    buckets = {}

    for point, index in zip(points, cell_indices):
        key = (int(index[0]), int(index[1]))
        buckets.setdefault(key, []).append(float(point[2]))

    cells = sorted(buckets)

    if len(cells) < 3:
        raise ValueError("Fewer than 3 occupied grid cells.")

    vertices = np.asarray([
        [
            xy_min[0] + (i + 0.5) * grid,
            xy_min[1] + (j + 0.5) * grid,
            float(np.median(buckets[(i, j)])),
        ]
        for i, j in cells
    ])

    try:
        triangulation = Delaunay(vertices[:, :2])
    except QhullError as exc:
        raise ValueError("Delaunay triangulation failed: {}".format(exc))

    faces = []
    rejected = 0

    for face in triangulation.simplices:
        tri = vertices[face]

        if triangle_max_edge(tri) > max_edge:
            rejected += 1
            continue

        if triangle_area(tri) < 1e-10:
            continue

        faces.append(face.tolist())

    mesh = make_mesh(vertices, faces)

    print("WARNING: Using fallback point-cloud triangulation.")
    print("Grid cells:", len(cells))
    print("Rejected triangles (edge limit):", rejected)
    print("Accepted floor triangles:", len(mesh.triangles))
    print("Floor mesh area: {:.3f} m2".format(mesh.get_surface_area()))

    return mesh, grid, "walkable.pcd (fallback)"


def vertical_plane_mesh(
    cloud,
    max_planes,
    distance,
    min_points,
    horizontal_z=0.25,
):
    """Extract dominant vertical planes and triangulate observed patches."""

    remaining = cloud
    meshes = []
    plane_info = []

    for _ in range(max_planes):
        if len(remaining.points) < min_points:
            break

        model, inliers = remaining.segment_plane(
            distance_threshold=distance,
            ransac_n=3,
            num_iterations=1500,
        )

        if len(inliers) < min_points:
            break

        points = np.asarray(remaining.points)
        plane_points = points[np.asarray(inliers, dtype=int)]

        normal = np.asarray(model[:3], dtype=float)
        normal /= max(np.linalg.norm(normal), 1e-12)

        if abs(normal[2]) <= horizontal_z:
            patch = o3d.geometry.PointCloud()
            patch.points = o3d.utility.Vector3dVector(plane_points)

            try:
                hull, _ = patch.compute_convex_hull()
                hull.compute_vertex_normals()

                area = float(hull.get_surface_area())
                bounds = plane_points.max(axis=0) - plane_points.min(axis=0)

                if len(hull.triangles) > 0 and 0 < area < 100:
                    meshes.append(hull)
                    plane_info.append({
                        "points": int(len(plane_points)),
                        "normal": normal.tolist(),
                        "bounds_min": plane_points.min(axis=0).tolist(),
                        "bounds_max": plane_points.max(axis=0).tolist(),
                        "bounds_size": bounds.tolist(),
                        "surface_area_m2": area,
                        "warning": (
                            "Convex hull may bridge doors or openings; "
                            "inspect before use."
                        ),
                    })
            except Exception as exc:
                print("WARNING: Could not build a wall patch:", exc)

        keep = np.ones(len(points), dtype=bool)
        keep[np.asarray(inliers, dtype=int)] = False
        remaining = remaining.select_by_index(np.flatnonzero(keep))

    if not meshes:
        return o3d.geometry.TriangleMesh(), plane_info

    combined = o3d.geometry.TriangleMesh()

    for part in meshes:
        combined += part

    combined.remove_duplicated_vertices()
    combined.remove_degenerate_triangles()
    combined.remove_unreferenced_vertices()
    combined.compute_vertex_normals()

    return combined, plane_info


def main():
    parser = argparse.ArgumentParser(
        description="Reconstruct a grid-based walkable floor and wall patches."
    )

    parser.add_argument("aligned", help="Path to aligned.pcd")
    parser.add_argument("out_dir", help="Output directory")
    parser.add_argument(
        "--walkable",
        help="Path to walkable.pcd; defaults to out_dir/walkable.pcd",
    )
    parser.add_argument(
        "--grid",
        type=float,
        default=0.08,
        help="Fallback grid spacing in metres (default: 0.08)",
    )
    parser.add_argument(
        "--max-edge",
        type=float,
        default=0.20,
        help="Maximum 3D triangle edge length in metres (default: 0.20)",
    )
    parser.add_argument(
        "--wall-distance",
        type=float,
        default=0.04,
        help="Wall plane RANSAC distance threshold in metres",
    )
    parser.add_argument(
        "--wall-min-points",
        type=int,
        default=500,
        help="Minimum inlier points for a wall plane",
    )
    parser.add_argument(
        "--max-walls",
        type=int,
        default=12,
        help="Maximum number of wall planes",
    )
    parser.add_argument(
        "--no-walls",
        action="store_true",
        help="Skip wall reconstruction",
    )

    args = parser.parse_args()

    out_dir = Path(args.out_dir).resolve()
    aligned_path = Path(args.aligned).resolve()
    walk_path = (
        Path(args.walkable).resolve()
        if args.walkable
        else out_dir / "walkable.pcd"
    )
    grid_path = out_dir / "walkable.npz"

    if not aligned_path.is_file():
        fail("Aligned point cloud not found: {}".format(aligned_path))

    if not grid_path.is_file() and not walk_path.is_file():
        fail(
            "Neither walkable.npz nor walkable.pcd was found in: {}".format(
                out_dir
            )
        )

    if args.grid <= 0 or args.max_edge <= 0 or args.wall_distance <= 0:
        fail("--grid, --max-edge and --wall-distance must be greater than 0.")

    if args.wall_min_points < 3 or args.max_walls < 0:
        fail("--wall-min-points must be >= 3 and --max-walls must be >= 0.")

    out_dir.mkdir(parents=True, exist_ok=True)

    try:
        print("Aligned file:", aligned_path)

        if grid_path.is_file():
            floor_mesh, used_grid, floor_source = floor_mesh_from_grid(
                grid_path,
                max_edge=args.max_edge,
            )
        else:
            print(
                "WARNING: walkable.npz not found; using the less reliable "
                "point-cloud fallback."
            )
            walk = load_cloud(walk_path)
            print("Walkable points:", len(walk.points))
            floor_mesh, used_grid, floor_source = floor_mesh_from_cloud(
                walk,
                grid=args.grid,
                max_edge=args.max_edge,
            )

        floor_path = out_dir / "floor_mesh.ply"

        if not o3d.io.write_triangle_mesh(
            str(floor_path),
            floor_mesh,
            write_ascii=False,
        ):
            fail("Failed to write floor_mesh.ply")

        wall_mesh = o3d.geometry.TriangleMesh()
        wall_info = []

        if not args.no_walls:
            aligned = load_cloud(aligned_path)
            print("Aligned points:", len(aligned.points))

            wall_mesh, wall_info = vertical_plane_mesh(
                aligned,
                args.max_walls,
                args.wall_distance,
                args.wall_min_points,
            )

            if len(wall_mesh.triangles):
                wall_path = out_dir / "wall_mesh.ply"

                if not o3d.io.write_triangle_mesh(
                    str(wall_path),
                    wall_mesh,
                    write_ascii=False,
                ):
                    print("WARNING: Failed to write wall_mesh.ply")

        floor_vertices = np.asarray(floor_mesh.vertices)
        floor_faces = np.asarray(floor_mesh.triangles)

        report = {
            "aligned_file": str(aligned_path),
            "floor_source": floor_source,
            "floor_mesh": str(floor_path),
            "floor_vertices": int(len(floor_vertices)),
            "floor_triangles": int(len(floor_faces)),
            "floor_grid_spacing_m": float(used_grid),
            "floor_max_edge_m": float(args.max_edge),
            "floor_bounds_min": floor_vertices.min(axis=0).tolist(),
            "floor_bounds_max": floor_vertices.max(axis=0).tolist(),
            "floor_surface_area_m2": float(floor_mesh.get_surface_area()),
            "wall_mesh": (
                str(out_dir / "wall_mesh.ply")
                if len(wall_mesh.triangles)
                else None
            ),
            "wall_vertices": int(len(wall_mesh.vertices)),
            "wall_triangles": int(len(wall_mesh.triangles)),
            "wall_planes": wall_info,
            "coordinate_frame": (
                "Aligned point-cloud frame; units assumed to be metres."
            ),
            "limitations": [
                "The preferred floor source is walkable.npz.",
                "Floor triangles are created only from local neighboring cells.",
                "Missing cells may leave holes; unobserved surfaces are not inferred.",
                "The fallback point-cloud triangulation is less reliable.",
                "Wall convex hull patches may bridge doors or openings.",
            ],
        }

        report_path = out_dir / "reconstruction.json"

        with report_path.open("w", encoding="utf-8") as file:
            json.dump(report, file, ensure_ascii=False, indent=2)

        print()
        print("Floor mesh:", floor_path)
        print("Floor vertices:", len(floor_mesh.vertices))
        print("Floor triangles:", len(floor_mesh.triangles))
        print(
            "Floor surface area: {:.3f} m2".format(
                floor_mesh.get_surface_area()
            )
        )

        if len(wall_mesh.triangles):
            print("Wall mesh:", out_dir / "wall_mesh.ply")
            print("Wall triangles:", len(wall_mesh.triangles))
        elif not args.no_walls:
            print("WARNING: No wall planes met the minimum point threshold.")

        print("Diagnostics:", report_path)

    except Exception as exc:
        fail("Mesh reconstruction failed: {}".format(exc))


if __name__ == "__main__":
    main()
